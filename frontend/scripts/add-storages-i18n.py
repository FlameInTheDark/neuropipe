def insert(text: str, nav_label: str, section_body: str) -> str:
    if "storages: {" in text or "storages:" in text.split("nav:", 1)[1][:600]:
        raise SystemExit("storages keys already present — refusing to double-insert")
    # 1) nav key after databases (plain str.replace — re.sub replacement
    # strings eat/mangle quotes, which produced literal \" artifacts before)
    nav_pattern = re.compile(r'\n    databases: "[^"]+",')
    match = nav_pattern.search(text)
    if not match:
        raise SystemExit("nav.databases anchor not found")
    nav_line = match.group(0)
    text = text.replace(nav_line, nav_line + '\n    storages: "' + nav_label + '",', 1)
    # 2) section before metrics
    anchor = "\n  metrics: {"
    if anchor not in text:
        raise SystemExit("metrics anchor not found")
    text = text.replace(anchor, "\n" + section_body + anchor, 1)
    return text


def main() -> None:
    for locale, spec in SECTIONS.items():
        path = LOCALES / f"{locale}.ts"
        original = path.read_text(encoding="utf-8")
        updated = insert(original, spec["nav"], spec["body"])
        path.write_text(updated, encoding="utf-8")
        print(f"{locale}: inserted nav.storages + storages section ({len(spec['body'].splitlines())} lines)")


if __name__ == "__main__":
    sys.exit(main())
